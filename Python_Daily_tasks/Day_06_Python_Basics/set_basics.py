numbers = {10, 20, 30, 40, 50}

print("Set:", numbers)

# Duplicate values are automatically removed
values = {10, 20, 30, 20, 10, 40}

print("Unique Values:", values)

# Adding an element
numbers.add(60)
print("After Adding:", numbers)

# Checking an element
print("Is 20 present?", 20 in numbers)

# Set Length
print("Set Length:", len(numbers))