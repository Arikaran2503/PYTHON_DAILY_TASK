fruits = ["Apple", "Banana", "Mango"]

# Append
fruits.append("Orange")
print("Append:", fruits)

# Insert
fruits.insert(1, "Grapes")
print("Insert:", fruits)

# Remove
fruits.remove("Banana")
print("Remove:", fruits)

# Pop
fruits.pop()
print("Pop:", fruits)

# Sort
fruits.sort()
print("Sort:", fruits)

# Reverse
fruits.reverse()
print("Reverse:", fruits)

# Count
print("Count:", fruits.count("Apple"))

# Index
print("Index:", fruits.index("Mango"))